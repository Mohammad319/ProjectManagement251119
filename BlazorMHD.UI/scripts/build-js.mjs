import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDir, '..');
const sourceFiles = [
    'wwwroot/js/src/00-core.js',
    'wwwroot/js/src/10-resizableDiv.js',
    'wwwroot/js/src/20-dialogDrag.js'
];
const outputFile = resolve(projectRoot, 'wwwroot/js/BlazorMHDUI.js');

const parts = await Promise.all(
    sourceFiles.map(async (relativePath) => {
        const fullPath = resolve(projectRoot, relativePath);
        return readFile(fullPath, 'utf8');
    })
);

const banner = '// Generated from wwwroot/js/src by scripts/build-js.mjs. Do not edit this file directly.\n\n';
await writeFile(outputFile, `${banner}${parts.join('\n\n')}\n`, 'utf8');
